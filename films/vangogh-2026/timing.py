"""src/voice.mp3 (one take) -> word times (faster-whisper) -> timing.js: line starts, word times, caption chunks, DUR.
usage: python3 timing.py"""
import json, re, unicodedata, difflib, subprocess, numpy as np
from faster_whisper import WhisperModel
L = json.load(open('lines.json'))
REP = {'dois mil e vinte e seis': '2026', 'cento e trinta e seis anos': '136 ANOS', 'cem milhões de dólares': 'US$ 100 MILHÕES', 'dois mil trabalhos': '2.000 OBRAS', 'dez anos': '10 ANOS'}
def nrm(w):
    w = unicodedata.normalize('NFD', w.lower()); w = ''.join(c for c in w if unicodedata.category(c) != 'Mn'); return re.sub(r'[^a-z0-9]', '', w)
NUM = {'2026': 'doismilevinteeseis', '71': 'setentaeum', '40': 'quarenta', '10': 'dez', '12': 'doze'}
pcm = np.frombuffer(subprocess.run(['ffmpeg', '-v', 'quiet', '-i', 'src/voice.mp3', '-ac', '1', '-ar', '16000', '-f', 's16le', '-'], capture_output=True).stdout, np.int16).astype(np.float32) / 32768
segs, _ = WhisperModel('small', compute_type='int8').transcribe(pcm, language='pt', word_timestamps=True)
asr = [{'w': w.word.strip(), 't0': w.start, 't1': w.end} for s in segs for w in s.words]
toks = [{'id': l['id'], 'w': w, 'n': nrm(w)} for l in L for w in l['text'].split()]
S = [t['n'] for t in toks]; A = [nrm(a['w']) for a in asr]
for t in toks: t['t0'] = t['t1'] = None
for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, S, A, autojunk=False).get_opcodes():
    if op == 'equal' or (op == 'replace' and i2 - i1 == j2 - j1):
        for k in range(i2 - i1): toks[i1 + k]['t0'], toks[i1 + k]['t1'] = asr[j1 + k]['t0'], asr[j1 + k]['t1']
    elif op == 'replace' and j2 > j1:
        a, b = asr[j1]['t0'], asr[j2 - 1]['t1']
        for k in range(i2 - i1): toks[i1 + k]['t0'] = a + (b - a) * k / (i2 - i1); toks[i1 + k]['t1'] = a + (b - a) * (k + 1) / (i2 - i1)
for i, x in enumerate(toks):
    if x['t0'] is None:
        p = next((toks[k]['t1'] for k in range(i - 1, -1, -1) if toks[k]['t1'] is not None), 0)
        x['t0'], x['t1'] = p, p + .2
VO = []
for l in L:
    ws = [t for t in toks if t['id'] == l['id']]; t0 = ws[0]['t0']
    VO.append({'id': l['id'], 't': round(t0, 3), 'd': round(ws[-1]['t1'] - t0, 3), 'words': [{'w': x['w'], 'n': x['n'], 't0': round(x['t0'] - t0, 3), 't1': round(x['t1'] - t0, 3)} for x in ws]})
DUR = round(asr[-1]['t1'] + 2.6, 2)
CAPS = []
for v in VO:
    if v['id'] == 'h1': continue
    ws, disp, i = v['words'], [], 0
    while i < len(ws):
        for k, r in REP.items():
            ks = k.split()
            if [x['n'] for x in ws[i:i + len(ks)]] == [nrm(q) for q in ks]:
                tail = re.sub(r'^[\wÀ-ÿ]+', '', ws[i + len(ks) - 1]['w']); disp.append({'w': r + tail, 't0': v['t'] + ws[i]['t0'], 'big': 1}); i += len(ks); break
        else: disp.append({'w': ws[i]['w'], 't0': v['t'] + ws[i]['t0']}); i += 1
    cur = []
    for d in disp:
        if d.get('big') and cur: CAPS.append(cur); cur = []
        cur.append(d)
        if d.get('big') or len(cur) >= 3 or sum(len(x['w']) for x in cur) >= 16 or re.search(r'[.,?!:]$', d['w']): CAPS.append(cur); cur = []
    if cur: CAPS.append(cur)
out = []
for k, c in enumerate(CAPS):
    nx = CAPS[k + 1][0]['t0'] if k + 1 < len(CAPS) else c[-1]['t0'] + 1
    out.append({'t0': c[0]['t0'] - .05, 't1': min(nx - .02, c[-1]['t0'] + 1.2), 'big': any(x.get('big') for x in c), 'words': [{'w': x['w'].replace('...', '').rstrip('.,:').upper(), 't0': x['t0']} for x in c]})
open('timing.js', 'w').write('// generated by timing.py from src/voice.mp3\nexport const VO = ' + json.dumps(VO, ensure_ascii=False) + ';\nexport const CAPS = ' + json.dumps(out, ensure_ascii=False) + f';\nexport const DUR = {DUR};\n')
print('DUR', DUR, ' '.join(f"{v['id']}@{v['t']}" for v in VO))
