"""voices/*.wav -> word times (faster-whisper) -> timing.js: VO start times, word times, caption chunks, DUR.
usage: python3 timing.py"""
import json, os, re, unicodedata, difflib, subprocess, numpy as np
from faster_whisper import WhisperModel
L = json.load(open('lines.json')); D = json.load(open('voices/dur.json'))
GAP = {'h1': .35, 'v6': .15, 'v7': .55, 'v9': .3, 'v10': 1.1}
REP = {'dois mil e vinte e seis': '2026', 'duzentos e cinco': '205', 'cinquenta': '50', 'dez minutos': '10 MINUTOS', 'dez milhões': '10 MILHÕES',
       'um metro e sessenta e nove': '1,69 M', 'um e setenta e cinco': '1,75 M'}
def nrm(w):
    w = unicodedata.normalize('NFD', w.lower()); w = ''.join(c for c in w if unicodedata.category(c) != 'Mn'); return re.sub(r'[^a-z0-9]', '', w)
m = WhisperModel('small', compute_type='int8')
def pcm(f): return np.frombuffer(subprocess.run(['ffmpeg','-v','quiet','-i',f,'-ac','1','-ar','16000','-f','s16le','-'],capture_output=True).stdout, np.int16).astype(np.float32) / 32768
VO, t = [], .12
for l in L:
    segs, _ = m.transcribe(pcm(f"voices/{l['id']}.wav"), language='pt', word_timestamps=True)
    asr = [{'w': w.word.strip(), 't0': w.start, 't1': w.end} for s in segs for w in s.words]
    toks = [{'w': w} for w in l['text'].split()]
    S = [nrm(x['w']) for x in toks]; A = [nrm(x['w']) for x in asr]
    for x in toks: x['t0'] = x['t1'] = None
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, S, A, autojunk=False).get_opcodes():
        if op == 'equal' or (op == 'replace' and i2 - i1 == j2 - j1):
            for k in range(i2 - i1): toks[i1 + k]['t0'], toks[i1 + k]['t1'] = asr[j1 + k]['t0'], asr[j1 + k]['t1']
        elif op == 'replace' and j2 > j1:
            a, b = asr[j1]['t0'], asr[j2 - 1]['t1']
            for k in range(i2 - i1): toks[i1 + k]['t0'] = a + (b - a) * k / (i2 - i1); toks[i1 + k]['t1'] = a + (b - a) * (k + 1) / (i2 - i1)
    for i, x in enumerate(toks):
        if x['t0'] is None:
            p = next((toks[k]['t1'] for k in range(i - 1, -1, -1) if toks[k]['t1'] is not None), 0)
            x['t0'], x['t1'] = p, p + .2
    VO.append({'id': l['id'], 't': round(t, 3), 'd': D[l['id']], 'words': [{'w': x['w'], 'n': nrm(x['w']), 't0': round(x['t0'], 3), 't1': round(x['t1'], 3)} for x in toks]})
    t += D[l['id']] + GAP.get(l['id'], .2)
DUR = round(t + 2.6, 2)
# captions: chunks of up to 3 words / 16 chars, numbers replaced, absolute times
CAPS = []
for v in VO:
    if v['id'] in ('h1',): continue
    ws, disp, i = v['words'], [], 0
    while i < len(ws):
        for k, r in REP.items():
            ks = k.split()
            if [x['n'] for x in ws[i:i + len(ks)]] == [nrm(q) for q in ks]:
                tail = re.sub(r'^[\wÀ-ÿ]+', '', ws[i + len(ks) - 1]['w']); disp.append({'w': r + tail, 't0': ws[i]['t0'], 'big': 1}); i += len(ks); break
        else: disp.append({'w': ws[i]['w'], 't0': ws[i]['t0']}); i += 1
    cur = []
    for d in disp:
        if d.get('big') and cur: CAPS.append(cur); cur = []
        cur.append(d)
        if d.get('big') or len(cur) >= 3 or sum(len(x['w']) for x in cur) >= 16 or re.search(r'[.,?!:]$', d['w']): CAPS.append(cur); cur = []
    if cur: CAPS.append(cur)
    for c in CAPS:
        if 'abs' not in c[0]:
            for x in c: x['abs'] = 1; x['t0'] = round(v['t'] + x['t0'], 3)
out = []
for k, c in enumerate(CAPS):
    nx = CAPS[k + 1][0]['t0'] if k + 1 < len(CAPS) else c[-1]['t0'] + 1
    out.append({'t0': c[0]['t0'] - .05, 't1': min(nx - .02, c[-1]['t0'] + 1.2), 'big': any(x.get('big') for x in c), 'words': [{'w': x['w'].replace('...', '').rstrip('.,:').upper(), 't0': x['t0']} for x in c]})
open('timing.js', 'w').write('// generated by timing.py from voices/\nexport const VO = ' + json.dumps(VO, ensure_ascii=False) + ';\nexport const CAPS = ' + json.dumps(out, ensure_ascii=False) + f';\nexport const DUR = {DUR};\n')
print('DUR', DUR, ' '.join(f"{v['id']}@{v['t']}" for v in VO))
